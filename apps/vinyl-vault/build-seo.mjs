#!/usr/bin/env node
// Vinyl Vault SEO build (Blake t479u). Run from anywhere:  node apps/vinyl-vault/build-seo.mjs [--lastmod YYYY-MM-DD]
// Generates, from apps/vinyl-vault/records.json and the same coverAlt() the vault uses at runtime:
//   1. sitemap.xml: the homepage <url> with the OG image plus one <image:image> (loc, title, caption) per cover.
//   2. apps/vinyl-vault/collection.jsonld: schema.org Collection (#vinyl-vault, creator #blake) with every MusicAlbum.
//      Crawler-only: nothing fetches it, so it costs visitors nothing. Since t495u index.html names it with one
//      <link rel="alternate" type="application/ld+json"> (browsers do not download alternate links; added by hand, not here).
//   3. index.html: one tiny Collection node (name, url, creator #blake, collectionSize) appended to the existing JSON-LD @graph,
//      replaced in place on re-runs. No albums are inlined there (load-time budget).
// Commit the outputs (GitHub Pages has no build step). Gate: checks/t479u-vv-seo.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { coverAlt, coverHead, coverTail } from './vinyl-vault.js';

const SITE = 'https://blakezuniga.com/';
const VAULT_DIR = 'apps/vinyl-vault/';
const COLL_ID = SITE + '#vinyl-vault';
const BLAKE_ID = SITE + '#blake';
const OG = SITE + 'assets/og/blake-zuniga-og.jpg';
const COVER_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*(?:\/[A-Za-z0-9][A-Za-z0-9._-]*)*\.(jpe?g|png|webp)$/i;

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const ai = process.argv.indexOf('--lastmod');
const lastmod = ai > 0 ? process.argv[ai + 1] : new Date().toISOString().slice(0, 10);
if (!/^\d{4}-\d{2}-\d{2}$/.test(lastmod)) throw new Error('bad --lastmod ' + lastmod);

const raw = JSON.parse(readFileSync(path.join(here, 'records.json'), 'utf8'));
if (!Array.isArray(raw)) throw new Error('records.json is not a list');
const records = raw.map((r) => {
  const artist = typeof r.artist === 'string' ? r.artist.trim() : '';
  const album = typeof r.album === 'string' ? r.album.trim() : '';
  if (!artist || !album || !COVER_RE.test(r.cover || '')) throw new Error('bad record ' + JSON.stringify(r.id));
  const year = Number.isInteger(r.year) && r.year >= 1900 && r.year <= 2100 ? r.year : 0;
  return { id: String(r.id), artist, album, year, image: SITE + VAULT_DIR + r.cover };
});

// ---- 1. image sitemap ----
const x = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const img = (loc, title, caption) => '    <image:image>\n' +
  `      <image:loc>${x(loc)}</image:loc>\n` +
  (title ? `      <image:title>${x(title)}</image:title>\n` : '') +
  (caption ? `      <image:caption>${x(caption)}</image:caption>\n` : '') +
  '    </image:image>\n';
const sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n' +
  '  <url>\n' +
  `    <loc>${SITE}</loc>\n` +
  `    <lastmod>${lastmod}</lastmod>\n` +
  img(OG) +
  '    <!-- Vinyl Vault covers: generated by apps/vinyl-vault/build-seo.mjs from records.json; do not edit by hand -->\n' +
  records.map((r) => img(r.image, coverHead(r) + ' vinyl, ' + coverTail(r.id), coverAlt(r))).join('') +
  '  </url>\n' +
  '</urlset>\n';
writeFileSync(path.join(root, 'sitemap.xml'), sitemap);

// ---- 2. full collection JSON-LD (crawler-only file) ----
const coll = {
  '@context': 'https://schema.org',
  '@type': 'Collection',
  '@id': COLL_ID,
  name: "Blake Zuniga's Vinyl Vault",
  url: SITE,
  creator: { '@id': BLAKE_ID },
  collectionSize: records.length,
  hasPart: records.map((r) => ({
    '@type': 'MusicAlbum',
    name: r.album,
    byArtist: { '@type': 'MusicGroup', name: r.artist },
    ...(r.year ? { datePublished: String(r.year) } : {}),
    image: r.image,
    description: coverAlt(r),
    isPartOf: { '@id': COLL_ID },
  })),
};
writeFileSync(path.join(here, 'collection.jsonld'), JSON.stringify(coll, null, 1) + '\n');

// ---- 3. tiny node in index.html's existing @graph ----
const node = JSON.stringify({ '@type': 'Collection', '@id': COLL_ID, name: coll.name, url: SITE, creator: { '@id': BLAKE_ID }, collectionSize: records.length }); // url: t495u
const htmlPath = path.join(root, 'index.html');
let html = readFileSync(htmlPath, 'utf8');
const open = '<script type="application/ld+json">';
const s = html.indexOf(open);
const e = s < 0 ? -1 : html.indexOf('</script>', s);
if (s < 0 || e < 0) throw new Error('index.html: JSON-LD block not found');
let block = html.slice(s + open.length, e);
const prev = block.indexOf(',{"@type":"Collection","@id":"' + COLL_ID + '"');
if (prev >= 0) { // remove the old node (brace-matched; no braces inside its strings)
  let d = 0, i = prev + 1;
  for (; i < block.length; i++) { if (block[i] === '{') d++; else if (block[i] === '}' && --d === 0) break; }
  block = block.slice(0, prev) + block.slice(i + 1);
}
if (!block.endsWith(']}')) throw new Error('index.html: JSON-LD @graph does not end with ]}');
block = block.slice(0, -2) + ',' + node + ']}';
JSON.parse(block); // never write broken JSON-LD
html = html.slice(0, s + open.length) + block + html.slice(e);
writeFileSync(htmlPath, html);

console.log(`build-seo: ${records.length} covers -> sitemap.xml (lastmod ${lastmod}), ${VAULT_DIR}collection.jsonld, index.html Collection node (${node.length} B)`);
